-- Create this table in the Supabase SQL editor before configuring the quote endpoint.
-- Keep Row Level Security enabled. The Cloudflare Function uses the service-role key
-- server-side; never expose that key in browser code or commit it to GitHub.

create table if not exists public.moving_quote_enquiries (
  id bigint generated by default as identity primary key,
  move_type text not null,
  origin text not null,
  destination text not null,
  home_size text not null,
  special_items text,
  move_date date not null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text,
  source text not null default 'website_quote_form',
  created_at timestamptz not null default now()
);

alter table public.moving_quote_enquiries enable row level security;

-- Do not add an anonymous INSERT policy. Submissions are written by the
-- Cloudflare Pages Function using a server-side service-role secret.